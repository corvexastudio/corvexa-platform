import { NextResponse } from 'next/server'
import { getTenantContext } from '@/lib/security/tenant-context'
import {
  listRecurringTemplates,
  createRecurringTemplate,
  generateDueRecurringJobs
} from '@/lib/jobs/recurring-manager'

export async function GET(request: Request) {
  const tenantResult = await getTenantContext('appointments:read')
  if (!tenantResult.ok) {
    return tenantResult.response
  }

  const { orgId, supabase } = tenantResult
  const result = await listRecurringTemplates(supabase, orgId)

  if (!result.success) {
    return NextResponse.json({ error: result.error }, { status: 400 })
  }

  return NextResponse.json({ templates: result.templates })
}

export async function POST(request: Request) {
  const tenantResult = await getTenantContext('appointments:manage')
  if (!tenantResult.ok) {
    return tenantResult.response
  }

  if (!['owner', 'admin', 'super_admin'].includes(tenantResult.role)) {
    return NextResponse.json(
      { error: "Forbidden: role 'member' lacks permission to manage recurring templates" },
      { status: 403 }
    )
  }

  const { orgId, supabase } = tenantResult
  const body = await request.json().catch(() => ({}))

  // Allow triggering autonomous generation directly
  if (body.action === 'generate') {
    const genResult = await generateDueRecurringJobs(supabase, { orgId })
    return NextResponse.json(genResult)
  }

  const {
    contactId,
    serviceId,
    assignedTo,
    title,
    description,
    cadence,
    dayOfWeek,
    preferredTimeStart,
    durationMinutes,
    amount,
    autoGenerateDaysAhead,
    firstScheduledDate
  } = body

  if (!contactId || !title?.trim() || !cadence) {
    return NextResponse.json(
      { error: 'Customer contact, title, and cadence are required' },
      { status: 400 }
    )
  }

  const result = await createRecurringTemplate(supabase, {
    orgId,
    contactId,
    serviceId: serviceId || undefined,
    assignedTo: assignedTo || undefined,
    title: title.trim(),
    description: description?.trim() || undefined,
    cadence,
    dayOfWeek: dayOfWeek !== undefined ? Number(dayOfWeek) : undefined,
    preferredTimeStart,
    durationMinutes: Number(durationMinutes) || 60,
    amount: Number(amount) || 0,
    autoGenerateDaysAhead: Number(autoGenerateDaysAhead) || 14,
    firstScheduledDate
  })

  if (!result.success) {
    return NextResponse.json({ error: result.error }, { status: 400 })
  }

  return NextResponse.json({ success: true, template: result.template })
}
