import { SupabaseClient } from '@supabase/supabase-js'
import { createJob } from './job-manager.ts'

export type RecurringCadence = 'weekly' | 'biweekly' | 'monthly' | 'quarterly' | 'biannual'
export type RecurringStatus = 'active' | 'paused' | 'cancelled'

export interface RecurringJobTemplate {
  id: string
  org_id: string
  contact_id: string
  service_id?: string | null
  assigned_to?: string | null
  title: string
  description?: string | null
  cadence: RecurringCadence
  day_of_week?: number | null // 0=Sun, 1=Mon, ..., 6=Sat
  preferred_time_start: string // HH:MM:SS
  duration_minutes: number
  amount: number
  status: RecurringStatus
  auto_generate_days_ahead: number
  last_generated_at?: string | null
  next_scheduled_date: string // YYYY-MM-DD
  created_at: string
  updated_at: string
}

export interface CreateRecurringTemplateInput {
  orgId: string
  contactId: string
  serviceId?: string
  assignedTo?: string
  title: string
  description?: string
  cadence: RecurringCadence
  dayOfWeek?: number
  preferredTimeStart?: string
  durationMinutes?: number
  amount?: number
  autoGenerateDaysAhead?: number
  firstScheduledDate?: string // YYYY-MM-DD
}

/**
 * Calculates the subsequent scheduled service date based on cadence.
 */
export function calculateNextScheduledDate(
  currentDateStr: string,
  cadence: RecurringCadence,
  targetDayOfWeek?: number | null
): string {
  const parts = currentDateStr.split('-').map(Number)
  const d = new Date(Date.UTC(parts[0], parts[1] - 1, parts[2]))

  switch (cadence) {
    case 'weekly':
      d.setUTCDate(d.getUTCDate() + 7)
      break
    case 'biweekly':
      d.setUTCDate(d.getUTCDate() + 14)
      break
    case 'monthly':
      d.setUTCMonth(d.getUTCMonth() + 1)
      break
    case 'quarterly':
      d.setUTCMonth(d.getUTCMonth() + 3)
      break
    case 'biannual':
      d.setUTCMonth(d.getUTCMonth() + 6)
      break
    default:
      d.setUTCDate(d.getUTCDate() + 7)
  }

  // If a specific day of week is preferred (0=Sun..6=Sat) for weekly/biweekly, adjust
  if (targetDayOfWeek !== undefined && targetDayOfWeek !== null && (cadence === 'weekly' || cadence === 'biweekly')) {
    const currentDay = d.getUTCDay()
    const diff = (targetDayOfWeek - currentDay + 7) % 7
    if (diff !== 0) {
      d.setUTCDate(d.getUTCDate() + diff)
    }
  }

  return d.toISOString().split('T')[0]
}

/**
 * Creates a new recurring maintenance/service template for a customer.
 */
export async function createRecurringTemplate(
  supabase: SupabaseClient,
  input: CreateRecurringTemplateInput
): Promise<{ success: boolean; template?: RecurringJobTemplate; error?: string }> {
  const {
    orgId,
    contactId,
    serviceId,
    assignedTo,
    title,
    description,
    cadence,
    dayOfWeek,
    preferredTimeStart = '09:00:00',
    durationMinutes = 60,
    amount = 0,
    autoGenerateDaysAhead = 14,
    firstScheduledDate
  } = input

  if (!title?.trim()) {
    return { success: false, error: 'Recurring plan title is required' }
  }

  if (!contactId) {
    return { success: false, error: 'Customer contact is required for recurring services' }
  }

  // Determine initial scheduled date
  const nextDate = firstScheduledDate || new Date().toISOString().split('T')[0]

  const { data: template, error } = await supabase
    .from('recurring_job_templates')
    .insert({
      org_id: orgId,
      contact_id: contactId,
      service_id: serviceId || null,
      assigned_to: assignedTo || null,
      title: title.trim(),
      description: description?.trim() || null,
      cadence,
      day_of_week: dayOfWeek ?? null,
      preferred_time_start: preferredTimeStart,
      duration_minutes: durationMinutes,
      amount: Number(amount) || 0,
      status: 'active',
      auto_generate_days_ahead: autoGenerateDaysAhead,
      next_scheduled_date: nextDate
    })
    .select('*')
    .single()

  if (error || !template) {
    return { success: false, error: error?.message || 'Failed to create recurring template' }
  }

  return { success: true, template: template as RecurringJobTemplate }
}

/**
 * Lists all recurring job plans for an organization with contact and service details.
 */
export async function listRecurringTemplates(
  supabase: SupabaseClient,
  orgId: string
): Promise<{ success: boolean; templates: any[]; error?: string }> {
  const { data, error } = await supabase
    .from('recurring_job_templates')
    .select(`
      *,
      contacts (
        id,
        name,
        phone,
        address
      ),
      services (
        id,
        name,
        price
      ),
      profiles (
        id,
        full_name
      )
    `)
    .eq('org_id', orgId)
    .order('created_at', { ascending: false })

  if (error) {
    return { success: false, templates: [], error: error.message }
  }

  return { success: true, templates: data || [] }
}

/**
 * Updates a recurring job template (status, cadence, amount, notes).
 */
export async function updateRecurringTemplate(
  supabase: SupabaseClient,
  templateId: string,
  orgId: string,
  updates: Partial<RecurringJobTemplate>
): Promise<{ success: boolean; template?: RecurringJobTemplate; error?: string }> {
  const payload: Record<string, any> = {
    ...updates,
    updated_at: new Date().toISOString()
  }

  const { data, error } = await supabase
    .from('recurring_job_templates')
    .update(payload)
    .eq('id', templateId)
    .eq('org_id', orgId)
    .select('*')
    .single()

  if (error || !data) {
    return { success: false, error: error?.message || 'Failed to update recurring template' }
  }

  return { success: true, template: data as RecurringJobTemplate }
}

/**
 * Deletes a recurring template.
 */
export async function deleteRecurringTemplate(
  supabase: SupabaseClient,
  templateId: string,
  orgId: string
): Promise<{ success: boolean; error?: string }> {
  const { error } = await supabase
    .from('recurring_job_templates')
    .delete()
    .eq('id', templateId)
    .eq('org_id', orgId)

  if (error) {
    return { success: false, error: error.message }
  }

  return { success: true }
}

/**
 * Autonomous Job Spawner:
 * Finds all active recurring templates due to be generated within their autoGenerateDaysAhead window.
 * Spawns real jobs and advances template next_scheduled_date atomically.
 */
export async function generateDueRecurringJobs(
  supabase: SupabaseClient,
  options?: { orgId?: string; limit?: number }
): Promise<{ success: boolean; generatedCount: number; errors: string[] }> {
  const today = new Date().toISOString().split('T')[0]
  const errors: string[] = []
  let generatedCount = 0

  let query = supabase
    .from('recurring_job_templates')
    .select('*')
    .eq('status', 'active')

  if (options?.orgId) {
    query = query.eq('org_id', options.orgId)
  }

  const { data: templates, error } = await query.limit(options?.limit || 50)

  if (error || !templates) {
    return { success: false, generatedCount: 0, errors: [error?.message || 'Failed to query recurring templates'] }
  }

  for (const t of templates) {
    try {
      // Check if within generation window: next_scheduled_date <= today + auto_generate_days_ahead
      const daysAhead = t.auto_generate_days_ahead || 14
      const targetThreshold = new Date(Date.now() + daysAhead * 24 * 60 * 60 * 1000).toISOString().split('T')[0]

      if (t.next_scheduled_date <= targetThreshold) {
        // Construct appointment timestamps
        const timePart = t.preferred_time_start || '09:00:00'
        const scheduledStart = `${t.next_scheduled_date}T${timePart.length === 5 ? `${timePart}:00` : timePart}Z`
        const durationMs = (t.duration_minutes || 60) * 60 * 1000
        const scheduledEnd = new Date(new Date(scheduledStart).getTime() + durationMs).toISOString()

        // 1. Spawn Job atomically via createJob
        const jobResult = await createJob(supabase, {
          orgId: t.org_id,
          contactId: t.contact_id,
          serviceId: t.service_id || undefined,
          assignedTo: t.assigned_to || undefined,
          title: t.title,
          description: t.description || `Recurring service generated from plan: ${t.title}`,
          scheduledStart,
          scheduledEnd,
          items: t.amount > 0 ? [
            {
              description: t.title,
              quantity: 1,
              unit_price: Number(t.amount)
            }
          ] : [],
          notes: `Cadence: ${t.cadence}. Auto-scheduled by CaptoDesk Autonomous Job Engine.`
        })

        if (jobResult.success && jobResult.job) {
          // Link recurring_template_id to spawned job
          await supabase
            .from('jobs')
            .update({ recurring_template_id: t.id })
            .eq('id', jobResult.job.id)

          // 2. Advance the template's next_scheduled_date
          const nextDate = calculateNextScheduledDate(t.next_scheduled_date, t.cadence, t.day_of_week)
          await supabase
            .from('recurring_job_templates')
            .update({
              last_generated_at: new Date().toISOString(),
              next_scheduled_date: nextDate,
              updated_at: new Date().toISOString()
            })
            .eq('id', t.id)

          generatedCount++
        } else {
          errors.push(`Template ${t.id}: ${jobResult.error}`)
        }
      }
    } catch (err: any) {
      errors.push(`Template ${t.id} exception: ${err?.message}`)
    }
  }

  return {
    success: errors.length === 0,
    generatedCount,
    errors
  }
}
