'use client'

import { useState } from 'react'
import { Modal } from '@/components/ui/modal'
import { Button } from '@/components/ui/button'
import { Input } from '@/components/ui/input'
import { Label } from '@/components/ui/label'
import { Repeat, Calendar, Clock, DollarSign, Loader2, Sparkles, CheckCircle2 } from 'lucide-react'
import { toast } from 'sonner'
import { type RecurringCadence } from '@/lib/jobs/recurring-manager'

interface CustomerOption {
  id: string
  name: string
  phone: string
}

interface ServiceOption {
  id: string
  name: string
  price?: number | null
  duration_minutes?: number
}

interface RecurringPlanModalProps {
  isOpen: boolean
  onClose: () => void
  customers: CustomerOption[]
  services: ServiceOption[]
  onSuccess?: () => void
}

const CADENCE_OPTIONS: { id: RecurringCadence; label: string; tradeHint: string }[] = [
  { id: 'weekly', label: 'Weekly', tradeHint: 'Lawn Mowing, Pool Service' },
  { id: 'biweekly', label: 'Bi-Weekly', tradeHint: 'Landscaping, Cleaning' },
  { id: 'monthly', label: 'Monthly', tradeHint: 'Filter Cleaning, Maintenance' },
  { id: 'quarterly', label: 'Quarterly', tradeHint: 'Pest Control, Water Care' },
  { id: 'biannual', label: 'Bi-Annual (Seasonal)', tradeHint: 'HVAC Spring A/C & Fall Furnace' }
]

const DAYS_OF_WEEK = [
  { id: 1, label: 'Mon' },
  { id: 2, label: 'Tue' },
  { id: 3, label: 'Wed' },
  { id: 4, label: 'Thu' },
  { id: 5, label: 'Fri' },
  { id: 6, label: 'Sat' },
  { id: 0, label: 'Sun' }
]

export function RecurringPlanModal({
  isOpen,
  onClose,
  customers,
  services,
  onSuccess
}: RecurringPlanModalProps) {
  const [contactId, setContactId] = useState('')
  const [serviceId, setServiceId] = useState('')
  const [title, setTitle] = useState('')
  const [cadence, setCadence] = useState<RecurringCadence>('weekly')
  const [dayOfWeek, setDayOfWeek] = useState<number>(1)
  const [preferredTime, setPreferredTime] = useState('09:00')
  const [durationMinutes, setDurationMinutes] = useState(60)
  const [amount, setAmount] = useState('75.00')
  const [startDate, setStartDate] = useState(new Date().toISOString().split('T')[0])
  const [submitting, setSubmitting] = useState(false)

  // Handle service selection auto-fill
  const handleServiceChange = (e: React.ChangeEvent<HTMLSelectElement>) => {
    const sId = e.target.value
    setServiceId(sId)
    const svc = services.find(s => s.id === sId)
    if (svc) {
      if (!title || services.some(s => s.name === title)) {
        setTitle(`Recurring ${svc.name}`)
      }
      if (svc.price) setAmount(Number(svc.price).toFixed(2))
      if (svc.duration_minutes) setDurationMinutes(svc.duration_minutes)
    }
  }

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault()
    if (!contactId) {
      toast.error('Please select a customer')
      return
    }
    if (!title.trim()) {
      toast.error('Please enter a plan title')
      return
    }

    setSubmitting(true)
    try {
      const res = await fetch('/api/client/recurring-jobs', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contactId,
          serviceId: serviceId || undefined,
          title: title.trim(),
          cadence,
          dayOfWeek,
          preferredTimeStart: `${preferredTime}:00`,
          durationMinutes: Number(durationMinutes) || 60,
          amount: Number(amount) || 0,
          firstScheduledDate: startDate,
          autoGenerateDaysAhead: 14
        })
      })

      const data = await res.json()
      if (res.ok && data.success) {
        toast.success('Recurring maintenance plan activated!')
        onSuccess?.()
        onClose()
      } else {
        toast.error(data.error || 'Failed to create recurring plan')
      }
    } catch {
      toast.error('Network error creating recurring plan')
    } finally {
      setSubmitting(false)
    }
  }

  return (
    <Modal
      open={isOpen}
      onOpenChange={(open) => !open && onClose()}
      title="Create Recurring Service Plan"
      description="Automate recurring visits that schedule themselves on your calendar and notify customers in advance."
      size="xl"
    >
      <form onSubmit={handleSubmit} className="space-y-4 pt-1">
        {/* Customer Selection */}
        <div className="space-y-1.5">
          <Label className="text-xs font-bold text-slate-700 dark:text-zinc-300">
            Select Customer <span className="text-red-500">*</span>
          </Label>
          <select
            value={contactId}
            onChange={(e) => setContactId(e.target.value)}
            required
            className="w-full text-xs h-9 px-3 rounded-xl border border-slate-200 dark:border-zinc-800 bg-white dark:bg-zinc-900 text-slate-900 dark:text-zinc-100"
          >
            <option value="">-- Choose customer --</option>
            {customers.map((c) => (
              <option key={c.id} value={c.id}>
                {c.name} ({c.phone})
              </option>
            ))}
          </select>
        </div>

        {/* Service Catalog Selection */}
        <div className="space-y-1.5">
          <Label className="text-xs font-bold text-slate-700 dark:text-zinc-300">
            Associated Service (Optional)
          </Label>
          <select
            value={serviceId}
            onChange={handleServiceChange}
            className="w-full text-xs h-9 px-3 rounded-xl border border-slate-200 dark:border-zinc-800 bg-white dark:bg-zinc-900 text-slate-900 dark:text-zinc-100"
          >
            <option value="">-- Custom or Generic Service --</option>
            {services.map((s) => (
              <option key={s.id} value={s.id}>
                {s.name} {s.price ? `($${Number(s.price).toFixed(2)})` : ''}
              </option>
            ))}
          </select>
        </div>

        {/* Plan Title */}
        <div className="space-y-1.5">
          <Label className="text-xs font-bold text-slate-700 dark:text-zinc-300">
            Plan Title <span className="text-red-500">*</span>
          </Label>
          <Input
            value={title}
            onChange={(e) => setTitle(e.target.value)}
            placeholder="e.g. Weekly Lawn Maintenance, Quarterly Pest Treatment"
            required
            className="text-xs h-9"
          />
        </div>

        {/* Cadence Selector */}
        <div className="space-y-1.5">
          <Label className="text-xs font-bold text-slate-700 dark:text-zinc-300">
            Service Cadence
          </Label>
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
            {CADENCE_OPTIONS.map((opt) => (
              <button
                key={opt.id}
                type="button"
                onClick={() => setCadence(opt.id)}
                className={`p-2.5 rounded-xl border text-left transition-all cursor-pointer ${
                  cadence === opt.id
                    ? 'bg-blue-50/80 dark:bg-blue-950/40 border-blue-500 text-blue-900 dark:text-blue-200 ring-1 ring-blue-500/40'
                    : 'bg-white dark:bg-zinc-900 border-slate-200 dark:border-zinc-800 text-slate-700 dark:text-zinc-300 hover:bg-slate-50 dark:hover:bg-zinc-850'
                }`}
              >
                <div className="flex items-center justify-between text-xs font-bold">
                  <span>{opt.label}</span>
                  {cadence === opt.id && <CheckCircle2 className="w-3.5 h-3.5 text-blue-600 dark:text-blue-400" />}
                </div>
                <div className="text-[10px] text-slate-400 dark:text-zinc-500 mt-0.5">
                  {opt.tradeHint}
                </div>
              </button>
            ))}
          </div>
        </div>

        {/* Day of Week for weekly/biweekly */}
        {(cadence === 'weekly' || cadence === 'biweekly') && (
          <div className="space-y-1.5">
            <Label className="text-xs font-bold text-slate-700 dark:text-zinc-300">
              Preferred Service Day
            </Label>
            <div className="flex gap-1.5 overflow-x-auto pb-1">
              {DAYS_OF_WEEK.map((d) => (
                <button
                  key={d.id}
                  type="button"
                  onClick={() => setDayOfWeek(d.id)}
                  className={`flex-1 py-1.5 px-2 rounded-lg text-xs font-bold border transition-colors cursor-pointer ${
                    dayOfWeek === d.id
                      ? 'bg-blue-600 text-white border-blue-600'
                      : 'bg-white dark:bg-zinc-900 text-slate-700 dark:text-zinc-300 border-slate-200 dark:border-zinc-800 hover:bg-slate-50'
                  }`}
                >
                  {d.label}
                </button>
              ))}
            </div>
          </div>
        )}

        {/* Start Date, Time & Pricing */}
        <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
          <div className="space-y-1.5">
            <Label className="text-xs font-bold text-slate-700 dark:text-zinc-300">
              First Visit Date
            </Label>
            <Input
              type="date"
              value={startDate}
              onChange={(e) => setStartDate(e.target.value)}
              className="text-xs h-9"
              required
            />
          </div>

          <div className="space-y-1.5">
            <Label className="text-xs font-bold text-slate-700 dark:text-zinc-300">
              Preferred Time
            </Label>
            <Input
              type="time"
              value={preferredTime}
              onChange={(e) => setPreferredTime(e.target.value)}
              className="text-xs h-9"
              required
            />
          </div>

          <div className="space-y-1.5">
            <Label className="text-xs font-bold text-slate-700 dark:text-zinc-300">
              Price Per Visit ($)
            </Label>
            <Input
              type="number"
              step="0.01"
              value={amount}
              onChange={(e) => setAmount(e.target.value)}
              className="text-xs h-9"
              required
            />
          </div>
        </div>

        {/* Modal Actions */}
        <div className="pt-3 flex justify-end gap-2 border-t border-slate-100 dark:border-zinc-800">
          <Button
            type="button"
            variant="outline"
            size="sm"
            onClick={onClose}
            className="text-xs h-9"
          >
            Cancel
          </Button>
          <Button
            type="submit"
            disabled={submitting}
            size="sm"
            className="text-xs h-9 px-4 font-bold bg-blue-600 hover:bg-blue-500 text-white shadow-xs cursor-pointer flex items-center gap-1.5"
          >
            {submitting ? (
              <>
                <Loader2 className="w-3.5 h-3.5 animate-spin" />
                <span>Activating...</span>
              </>
            ) : (
              <>
                <Repeat className="w-3.5 h-3.5" />
                <span>Activate Recurring Plan</span>
              </>
            )}
          </Button>
        </div>
      </form>
    </Modal>
  )
}
